-- ═══════════════════════════════════════════════════════════════════════════
--  LlamadoAPP · Storyboard: esquema versionado y endurecimiento
--
--  La tabla y el bucket se crearon desde el proyecto original (Storyboard
--  Studio) y no estaban versionados. Esta migración los deja reproducibles en
--  cualquier entorno y aplica seis correcciones:
--
--    1. El bucket deja de aceptar escrituras anónimas.
--    2. Esquema completo (tabla, FK, bucket y políticas) en el repo.
--    3. `updated_at` con trigger: auditoría y detección de ediciones cruzadas.
--    4. `panel_count` generada: la lista ya no baja los JSONB completos.
--    5. (cliente) ids de viñeta con crypto.randomUUID.
--    6. (cliente) las imágenes se redimensionan antes de subirse.
--
--  Todo es idempotente: se puede aplicar sobre la base actual (que ya tiene la
--  tabla y el bucket) o sobre un entorno nuevo creado desde cero.
--
--  Aplicar con:  supabase db push
-- ══════════════════════════════════════════════════════════════════════════

-- ─────────────────────────────────────────────────────────────
--  Tabla
-- ─────────────────────────────────────────────────────────────
create table if not exists public.storyboards (
  id          bigint generated by default as identity primary key,
  proyecto_id bigint not null references public.proyectos(id) on delete cascade,
  name        text   not null,
  panels      jsonb  not null default '[]'::jsonb,
  locutions   jsonb  not null default '[]'::jsonb,
  created_at  timestamptz not null default timezone('utc', now())
);

comment on table public.storyboards is
  'Storyboard de un proyecto: viñetas (panels) y sus locuciones, alineadas por índice.';

comment on column public.storyboards.panels is
  'Arreglo JSON: [{ id, filename, image_path, image_url, description, version }].';

comment on column public.storyboards.locutions is
  'Arreglo de textos; locutions[i] corresponde a panels[i] por índice.';

-- Columnas nuevas sobre una tabla que ya existía.
alter table public.storyboards
  add column if not exists updated_at timestamptz not null default timezone('utc', now());

-- La lista del panel solo necesita el conteo, no el JSON completo.
alter table public.storyboards
  add column if not exists panel_count integer
  generated always as (jsonb_array_length(panels)) stored;

comment on column public.storyboards.panel_count is
  'Cantidad de viñetas, calculada por Postgres para no bajar `panels` al listar.';

-- ─────────────────────────────────────────────────────────────
--  Auditoría de escritura
-- ─────────────────────────────────────────────────────────────
create or replace function public.storyboards_touch_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

comment on function public.storyboards_touch_updated_at() is
  'Mantiene storyboards.updated_at al día en cada UPDATE.';

drop trigger if exists storyboards_touch_updated_at on public.storyboards;
create trigger storyboards_touch_updated_at
  before update on public.storyboards
  for each row
  execute function public.storyboards_touch_updated_at();

-- ─────────────────────────────────────────────────────────────
--  Índices
-- ─────────────────────────────────────────────────────────────
create index if not exists storyboards_proyecto_created_idx
  on public.storyboards (proyecto_id, created_at desc);

-- ─────────────────────────────────────────────────────────────
--  RLS: lectura pública del contenido, escritura solo con sesión
--
--  La lectura anónima se conserva porque el link de presentación
--  (`?mode=presenter`) la necesita cuando se habilite; si se decide cerrarla,
--  basta con eliminar la política `storyboards_select_anon`.
-- ─────────────────────────────────────────────────────────────
alter table public.storyboards enable row level security;

drop policy if exists "Allow public to read storyboards" on public.storyboards;
drop policy if exists "Allow authenticated users to read all storyboards" on public.storyboards;
drop policy if exists "Permitir inserción pública/anon" on public.storyboards;
drop policy if exists "Permitir actualización pública/anon" on public.storyboards;
drop policy if exists "Permitir eliminación pública/anon" on public.storyboards;

create policy storyboards_select_anon
  on public.storyboards for select
  to anon
  using (true);

create policy storyboards_select_authenticated
  on public.storyboards for select
  to authenticated
  using (true);

create policy storyboards_insert_authenticated
  on public.storyboards for insert
  to authenticated
  with check (true);

create policy storyboards_update_authenticated
  on public.storyboards for update
  to authenticated
  using (true)
  with check (true);

create policy storyboards_delete_authenticated
  on public.storyboards for delete
  to authenticated
  using (true);

-- Privilegios de tabla: la RLS filtra, pero el grant por defecto dejaba a
-- `anon` con INSERT/UPDATE/DELETE declarados. Se revocan explícitamente.
revoke all on table public.storyboards from anon;
grant select on table public.storyboards to anon;
grant select, insert, update, delete on table public.storyboards to authenticated;

do $$
begin
  if exists (select 1 from pg_class where relkind = 'S' and relname = 'storyboards_id_seq') then
    execute 'grant usage, select on sequence public.storyboards_id_seq to authenticated';
  end if;
end $$;

-- ─────────────────────────────────────────────────────────────
--  Bucket
-- ─────────────────────────────────────────────────────────────
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'storyboards',
  'storyboards',
  true,
  15 * 1024 * 1024,
  array['image/jpeg', 'image/png', 'image/webp', 'image/avif']
)
on conflict (id) do update
  set public             = excluded.public,
      file_size_limit    = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- ─────────────────────────────────────────────────────────────
--  Políticas del bucket
--
--  Antes: `anon,authenticated` podía subir, actualizar y borrar cualquier
--  objeto con la anon key, que viaja en el bundle del cliente. Ahora solo
--  `authenticated`. La lectura sigue abierta (bucket público + política).
-- ─────────────────────────────────────────────────────────────
drop policy if exists "Permitir lectura de imágenes anon" on storage.objects;
drop policy if exists "Permitir subida de imágenes anon" on storage.objects;
drop policy if exists "Permitir actualizar imágenes anon" on storage.objects;
drop policy if exists "Permitir eliminar imágenes anon" on storage.objects;
drop policy if exists storyboards_lectura on storage.objects;
drop policy if exists storyboards_subida_authenticated on storage.objects;
drop policy if exists storyboards_actualizacion_authenticated on storage.objects;
drop policy if exists storyboards_borrado_authenticated on storage.objects;

create policy storyboards_lectura
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'storyboards');

create policy storyboards_subida_authenticated
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'storyboards');

create policy storyboards_actualizacion_authenticated
  on storage.objects for update
  to authenticated
  using (bucket_id = 'storyboards')
  with check (bucket_id = 'storyboards');

create policy storyboards_borrado_authenticated
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'storyboards');
