-- ═══════════════════════════════════════════════════════════════════════════
--  LlamadoAPP · App móvil (/movil)
--  Registro de accesos y confirmaciones de llamado, persona por persona.
--
--  Aplicar con:  supabase db push
--  (o pegar el archivo completo en el SQL Editor del proyecto)
--
--  Flujo:
--   1. El admin genera un token por persona → admin_generar_invitaciones(llamado_id)
--   2. Al abrir su link personal la app llama → movil_registrar_evento(token, 'acceso')
--   3. Al confirmar la app llama          → movil_registrar_evento(token, 'confirmacion')
--      Los links sin token confirman con → movil_confirmar_por_nombre(llamado_id, crew_id)
--
--  Reglas:
--   · Solo se guarda el PRIMER acceso histórico por persona.
--   · Solo se guarda UNA confirmación por persona (idempotente).
--   · Las tablas quedan cerradas a `anon`: todas las escrituras pasan por
--     funciones SECURITY DEFINER que validan el token.
-- ═══════════════════════════════════════════════════════════════════════════

-- ─────────────────────────────────────────────────────────────
--  Tablas
-- ─────────────────────────────────────────────────────────────
create table if not exists public.crew_invitaciones (
  id          bigint generated by default as identity primary key,
  llamado_id  bigint not null references public.llamados(id) on delete cascade,
  crew_id     bigint not null references public.crew(id) on delete cascade,
  token       uuid   not null default gen_random_uuid(),
  creado_en   timestamptz not null default now(),
  constraint crew_invitaciones_llamado_crew_key unique (llamado_id, crew_id),
  constraint crew_invitaciones_token_key unique (token)
);

comment on table public.crew_invitaciones is
  'Token personal (uuid) que identifica a cada miembro del crew en un llamado.';

create table if not exists public.llamado_respuestas (
  id             bigint generated by default as identity primary key,
  llamado_id     bigint not null references public.llamados(id) on delete cascade,
  crew_id        bigint not null references public.crew(id) on delete cascade,
  invitacion_id  bigint references public.crew_invitaciones(id) on delete set null,
  evento         text not null check (evento in ('acceso', 'confirmacion')),
  user_agent     text,
  plataforma     text,
  creado_en      timestamptz not null default now()
);

comment on table public.llamado_respuestas is
  'Eventos de la app móvil: primer acceso al link y confirmación del llamado. No se guarda IP.';

-- Un solo acceso histórico y una sola confirmación por persona y llamado.
create unique index if not exists llamado_respuestas_primer_acceso
  on public.llamado_respuestas (llamado_id, crew_id) where evento = 'acceso';

create unique index if not exists llamado_respuestas_confirmacion_unica
  on public.llamado_respuestas (llamado_id, crew_id) where evento = 'confirmacion';

create index if not exists llamado_respuestas_llamado_idx
  on public.llamado_respuestas (llamado_id, evento);

-- ─────────────────────────────────────────────────────────────
--  RLS y permisos
--  Las tablas NO son accesibles con la anon key: solo el admin
--  autenticado las lee, y el público escribe a través de las RPC.
-- ─────────────────────────────────────────────────────────────
alter table public.crew_invitaciones enable row level security;
alter table public.llamado_respuestas enable row level security;

revoke all on table public.crew_invitaciones from anon, authenticated;
revoke all on table public.llamado_respuestas from anon, authenticated;

grant select, insert, update, delete on table public.crew_invitaciones to authenticated;
grant select on table public.llamado_respuestas to authenticated;

do $$
begin
  if exists (select 1 from pg_class where relkind = 'S' and relname = 'crew_invitaciones_id_seq') then
    execute 'grant usage, select on sequence public.crew_invitaciones_id_seq to authenticated';
  end if;
end $$;

drop policy if exists crew_invitaciones_admin on public.crew_invitaciones;
create policy crew_invitaciones_admin on public.crew_invitaciones
  for all to authenticated using (true) with check (true);

drop policy if exists llamado_respuestas_admin_lectura on public.llamado_respuestas;
create policy llamado_respuestas_admin_lectura on public.llamado_respuestas
  for select to authenticated using (true);

-- ─────────────────────────────────────────────────────────────
--  RPC pública · registrar acceso o confirmación con token
-- ─────────────────────────────────────────────────────────────
create or replace function public.movil_registrar_evento(p_token uuid, p_evento text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_inv        public.crew_invitaciones;
  v_confirmado timestamptz;
  v_nombre     text;
  v_headers    jsonb;
begin
  if p_evento is null or p_evento not in ('acceso', 'confirmacion') then
    return jsonb_build_object('ok', false, 'error', 'evento_invalido');
  end if;

  select * into v_inv from public.crew_invitaciones where token = p_token;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'token_invalido');
  end if;

  select nombre into v_nombre from public.crew where id = v_inv.crew_id;

  begin
    v_headers := nullif(current_setting('request.headers', true), '')::jsonb;
  exception when others then
    v_headers := null;
  end;

  insert into public.llamado_respuestas
    (llamado_id, crew_id, invitacion_id, evento, user_agent, plataforma)
  values (
    v_inv.llamado_id,
    v_inv.crew_id,
    v_inv.id,
    p_evento,
    nullif(left(coalesce(v_headers->>'user-agent', ''), 400), ''),
    nullif(left(trim(both '"' from coalesce(v_headers->>'sec-ch-ua-platform', '')), 40), '')
  )
  on conflict do nothing;

  select min(creado_en) into v_confirmado
    from public.llamado_respuestas
   where llamado_id = v_inv.llamado_id
     and crew_id = v_inv.crew_id
     and evento = 'confirmacion';

  return jsonb_build_object(
    'ok', true,
    'llamado_id', v_inv.llamado_id,
    'crew_id', v_inv.crew_id,
    'nombre', v_nombre,
    'confirmado_en', v_confirmado,
    'evento', p_evento
  );
end;
$$;

comment on function public.movil_registrar_evento(uuid, text) is
  'App móvil: registra el primer acceso y la confirmación del llamado a partir del token personal.';

-- ─────────────────────────────────────────────────────────────
--  RPC pública · confirmar sin token (link general)
-- ─────────────────────────────────────────────────────────────
create or replace function public.movil_confirmar_por_nombre(p_llamado_id bigint, p_crew_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_nombre      text;
  v_confirmado  timestamptz;
  v_asignado    boolean;
begin
  select true, c.nombre
    into v_asignado, v_nombre
    from public.crew_llamado cl
    join public.crew c on c.id = cl.crew_id
   where cl.llamado_id = p_llamado_id
     and cl.crew_id = p_crew_id
   limit 1;

  if v_asignado is not true then
    return jsonb_build_object('ok', false, 'error', 'crew_no_asignado');
  end if;

  insert into public.llamado_respuestas (llamado_id, crew_id, evento)
  values (p_llamado_id, p_crew_id, 'confirmacion')
  on conflict do nothing;

  select min(creado_en) into v_confirmado
    from public.llamado_respuestas
   where llamado_id = p_llamado_id
     and crew_id = p_crew_id
     and evento = 'confirmacion';

  return jsonb_build_object(
    'ok', true,
    'llamado_id', p_llamado_id,
    'crew_id', p_crew_id,
    'nombre', v_nombre,
    'confirmado_en', v_confirmado,
    'evento', 'confirmacion'
  );
end;
$$;

comment on function public.movil_confirmar_por_nombre(bigint, bigint) is
  'App móvil: confirma el llamado de una persona cuando se abrió un link sin token.';

-- ─────────────────────────────────────────────────────────────
--  RPC admin · generar invitaciones y ver el resumen
-- ─────────────────────────────────────────────────────────────
create or replace function public.admin_generar_invitaciones(p_llamado_id bigint)
returns table (
  crew_id      bigint,
  nombre       text,
  cargo        text,
  departamento text,
  hora_llamado text,
  celular      text,
  orden        numeric,
  token        uuid,
  creado_en    timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(auth.role(), '') not in ('authenticated', 'service_role') then
    raise exception 'No autorizado' using errcode = '42501';
  end if;

  insert into public.crew_invitaciones (llamado_id, crew_id)
  select cl.llamado_id, cl.crew_id
    from public.crew_llamado cl
   where cl.llamado_id = p_llamado_id
  on conflict (llamado_id, crew_id) do nothing;

  return query
  select ci.crew_id,
         c.nombre,
         c.cargo,
         c.departamento,
         coalesce(cl.hora_llamado, c.llamado_hora)::text,
         c.celular,
         cl.orden,
         ci.token,
         ci.creado_en
    from public.crew_invitaciones ci
    join public.crew c on c.id = ci.crew_id
    left join public.crew_llamado cl
      on cl.llamado_id = ci.llamado_id and cl.crew_id = ci.crew_id
   where ci.llamado_id = p_llamado_id
   order by cl.orden nulls last, c.nombre;
end;
$$;

comment on function public.admin_generar_invitaciones(bigint) is
  'Admin: crea los tokens que falten para el llamado y devuelve la lista con su link.';

create or replace function public.admin_resumen_confirmaciones(p_llamado_id bigint)
returns table (
  crew_id       bigint,
  nombre        text,
  cargo         text,
  departamento  text,
  hora_llamado  text,
  celular       text,
  orden         numeric,
  token         uuid,
  acceso_en     timestamptz,
  confirmado_en timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(auth.role(), '') not in ('authenticated', 'service_role') then
    raise exception 'No autorizado' using errcode = '42501';
  end if;

  return query
  select ci.crew_id,
         c.nombre,
         c.cargo,
         c.departamento,
         coalesce(cl.hora_llamado, c.llamado_hora)::text,
         c.celular,
         cl.orden,
         ci.token,
         (select min(r.creado_en) from public.llamado_respuestas r
           where r.llamado_id = ci.llamado_id and r.crew_id = ci.crew_id and r.evento = 'acceso'),
         (select min(r.creado_en) from public.llamado_respuestas r
           where r.llamado_id = ci.llamado_id and r.crew_id = ci.crew_id and r.evento = 'confirmacion')
    from public.crew_invitaciones ci
    join public.crew c on c.id = ci.crew_id
    left join public.crew_llamado cl
      on cl.llamado_id = ci.llamado_id and cl.crew_id = ci.crew_id
   where ci.llamado_id = p_llamado_id
   order by cl.orden nulls last, c.nombre;
end;
$$;

comment on function public.admin_resumen_confirmaciones(bigint) is
  'Admin: quién abrió el link y quién confirmó su llamado.';

